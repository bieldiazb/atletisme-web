/**
 * Donada una marca (string), el nom de la prova i el sexe,
 * retorna els punts FCA per interpolació lineal.
 *
 * @param {string} marca     — ex: "12.45", "7.90", "1:27.8"
 * @param {string} nomProva  — nom tal com apareix a Firestore
 * @param {string} sexe      — "M" o "F"
 * @returns {number|null}    — puntuació 1-1000 o null si fora de rang / prova no trobada
 */
export function getPuntsFCA(marca, nomProva, sexe) {
  const taula = sexe === "F" ? TAULA_F : TAULA_M
  const provaKey = mapProvaToKey(nomProva, sexe)
  if (!provaKey || !taula[provaKey]) return null

  const valorMarca = parseFCAMarca(marca)
  if (valorMarca == null) return null

  const config = PROVA_CONFIG[provaKey]
  if (!config) return null

  const entrades = taula[provaKey]
  const millorFirst = config.millorEs === "menor"

  for (let i = 0; i < entrades.length; i++) {
    const e = entrades[i]
    if (millorFirst) {
      if (valorMarca <= e.valor) return e.punts
      if (i + 1 < entrades.length) {
        const seg = entrades[i + 1]
        if (valorMarca <= seg.valor) {
          const frac = (valorMarca - e.valor) / (seg.valor - e.valor)
          return Math.round(e.punts - frac * (e.punts - seg.punts))
        }
      }
    } else {
      if (valorMarca >= e.valor) return e.punts
      if (i + 1 < entrades.length) {
        const seg = entrades[i + 1]
        if (valorMarca >= seg.valor) {
          const frac = (e.valor - valorMarca) / (e.valor - seg.valor)
          return Math.round(e.punts - frac * (e.punts - seg.punts))
        }
      }
    }
  }
  return null
}

