/**
 * Converteix una marca en format string a un valor numèric en segons o metres.
 * Formats suportats:
 *   "8.54"     → 8.54
 *   "8*54"     → 8.54  (asterisk = punt decimal)
 *   "1:27"     → 87.0
 *   "1:27.8"   → 87.8
 *   "1:27*8"   → 87.8
 */
export function parseFCAMarca(marca) {
  if (!marca || marca === "—" || marca === "-") return null
  const s = String(marca).trim().replace(/\s/g, "")

  const colonMatch = s.match(/^(\d+):(\d+)(?:[*.,](\d+))?$/)
  if (colonMatch) {
    const mins = parseInt(colonMatch[1], 10)
    const secs = parseInt(colonMatch[2], 10)
    const decs = colonMatch[3] ? parseFloat("0." + colonMatch[3]) : 0
    return mins * 60 + secs + decs
  }

  const asteriskMatch = s.match(/^(\d+)\*(\d+)$/)
  if (asteriskMatch) return parseFloat(asteriskMatch[1] + "." + asteriskMatch[2])

  const n = parseFloat(s.replace(",", "."))
  return isNaN(n) ? null : n
}

/**
 * Mapeja el nom de la prova (tal com apareix a Firestore) a la clau de la taula FCA.
 * Suporta noms en català i abreviatures habituals.
 *
 * @param {string} nomProva  — ex: "60 mll", "1000 mll", "llargada", "pes"
 * @param {string} sexe      — "M" o "F"
 * @returns {string|null}
 */
export function mapProvaToKey(nomProva, sexe) {
  if (!nomProva) return null
  const n = nomProva.toLowerCase().trim()

  if (sexe === "M") {
    if (n.includes("1000")) return "1000M"
    if (n.includes("400"))  return "400M"
    if (n.includes("vortex") || n.includes("pilota")) return "PILOTA_M"
    if (n.match(/\b60\b/) && !n.includes("tanq") && !n.includes("mt")) return "60M"
    if (n.includes("80")  && !n.includes("t") && !n.includes("tanq")) return "80M"
    if (n.includes("100") && !n.includes("t") && !n.includes("tanq")) return "100M"
    if (n.includes("80")  && (n.includes("t") || n.includes("tanq") || n.includes("mt"))) return "80TM"
    if (n.includes("110") && (n.includes("t") || n.includes("tanq") || n.includes("mt"))) return "110TM"
    if (n.includes("llarg")) return "LLARGADA_M"
    if (n.includes("alç") || n.includes("alca")) return "ALCADA_M"
    if (n.includes("perxa")) return "PERXA_M"
    if (n.includes("pes"))   return "PES_M"
    if (n.includes("disc"))  return "DISC_M"
    if (n.includes("javelina") || n.includes("javelin")) return "JAVELINA_M"
  }

  if (sexe === "F") {
    if (n.includes("1000")) return "1000F"
    if (n.includes("600"))  return "600F"
    if (n.includes("400"))  return "400F"
    if (n.includes("vortex") || n.includes("pilota")) return "PILOTA_F"
    if (n.match(/\b60\b/) && !n.includes("tanq") && !n.includes("mt")) return "60F"
    if (n.includes("60")  && (n.includes("t") || n.includes("tanq") || n.includes("mt"))) return "60TF"
    if (n.includes("80")  && (n.includes("t") || n.includes("tanq") || n.includes("mt"))) return "80TF"
    if (n.includes("100") && (n.includes("t") || n.includes("tanq") || n.includes("mt"))) return "100TF"
    if (n.includes("alç") || n.includes("alca")) return "ALCADA_F"
    if (n.includes("llarg")) return "LLARGADA_F"
    if (n.includes("pes"))   return "PES_F"
    if (n.includes("javelina") || n.includes("javelin")) return "JAVELINA_F"
  }

  return null
}

